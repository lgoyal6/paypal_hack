// paydrill types: infer TypeScript types and zod validators from recorded
// PayPal events, snapshot each event type's shape, and warn when it drifts.
import { existsSync, mkdirSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import type { PayPalEvent } from '../contract.ts';

export type Shape =
  | { kind: 'string' | 'number' | 'boolean' | 'null' | 'unknown' }
  | { kind: 'array'; of: Shape }
  | { kind: 'object'; fields: Record<string, { shape: Shape; optional: boolean }> }
  | { kind: 'union'; of: Shape[] };

export function infer(v: unknown): Shape {
  if (v === null) return { kind: 'null' };
  if (Array.isArray(v)) return { kind: 'array', of: v.map(infer).reduce(merge, { kind: 'unknown' }) };
  if (typeof v === 'object') {
    return { kind: 'object', fields: Object.fromEntries(Object.entries(v as object).map(([k, x]) => [k, { shape: infer(x), optional: false }])) };
  }
  const t = typeof v;
  return t === 'string' || t === 'number' || t === 'boolean' ? { kind: t } : { kind: 'unknown' };
}

const same = (a: Shape, b: Shape) => JSON.stringify(a) === JSON.stringify(b);

export function merge(a: Shape, b: Shape): Shape {
  if (a.kind === 'unknown') return b;
  if (b.kind === 'unknown') return a;
  if (a.kind === 'object' && b.kind === 'object') {
    const keys = new Set([...Object.keys(a.fields), ...Object.keys(b.fields)]);
    return { kind: 'object', fields: Object.fromEntries([...keys].map((k) => {
      const x = a.fields[k], y = b.fields[k];
      if (x && y) return [k, { shape: merge(x.shape, y.shape), optional: x.optional || y.optional }];
      return [k, { shape: (x ?? y).shape, optional: true }];
    })) };
  }
  if (a.kind === 'array' && b.kind === 'array') return { kind: 'array', of: merge(a.of, b.of) };
  if (same(a, b)) return a;
  const parts = [...(a.kind === 'union' ? a.of : [a]), ...(b.kind === 'union' ? b.of : [b])];
  return { kind: 'union', of: parts.filter((p, i) => parts.findIndex((q) => same(p, q)) === i) };
}

const key = (k: string) => (/^[A-Za-z_$][\w$]*$/.test(k) ? k : JSON.stringify(k));

export function toTs(s: Shape, indent = ''): string {
  switch (s.kind) {
    case 'array': { const inner = toTs(s.of, indent); return s.of.kind === 'union' ? `(${inner})[]` : `${inner}[]`; }
    case 'union': return s.of.map((x) => toTs(x, indent)).join(' | ');
    case 'object': {
      const i2 = indent + '  ';
      return `{\n${Object.entries(s.fields).map(([k, f]) => `${i2}${key(k)}${f.optional ? '?' : ''}: ${toTs(f.shape, i2)};`).join('\n')}\n${indent}}`;
    }
    default: return s.kind;
  }
}

export function toZod(s: Shape, indent = ''): string {
  switch (s.kind) {
    case 'array': return `z.array(${toZod(s.of, indent)})`;
    case 'union': return `z.union([${s.of.map((x) => toZod(x, indent)).join(', ')}])`;
    case 'object': {
      const i2 = indent + '  ';
      return `z.object({\n${Object.entries(s.fields).map(([k, f]) => `${i2}${key(k)}: ${toZod(f.shape, i2)}${f.optional ? '.optional()' : ''},`).join('\n')}\n${indent}})`;
    }
    default: return s.kind.startsWith("'") ? `z.literal(${s.kind})` : `z.${s.kind}()`;
  }
}

const typeName = (eventType: string) => eventType.toLowerCase().split(/[._-]/).map((p) => p[0].toUpperCase() + p.slice(1)).join('') + 'Event';

/** Load recorded events from a directory of JSON files (one event, or an array, per file). */
export function loadEvents(dir: string): PayPalEvent[] {
  return readdirSync(dir).filter((f) => f.endsWith('.json')).flatMap((f) => {
    const v = JSON.parse(readFileSync(join(dir, f), 'utf8'));
    return (Array.isArray(v) ? v : [v]).map(({ _source, ...e }: any) => e as PayPalEvent);
  });
}

export function shapesByType(events: PayPalEvent[]): Map<string, Shape> {
  const m = new Map<string, Shape>();
  for (const e of events) m.set(e.event_type, merge(m.get(e.event_type) ?? { kind: 'unknown' }, infer(e)));
  return new Map([...m].sort(([a], [b]) => a.localeCompare(b)));
}

export function generate(shapes: Map<string, Shape>): { types: string; zod: string } {
  const head = '// Generated by `paydrill types` from recorded PayPal sandbox events. Do not edit.\n';
  const names = [...shapes.keys()].map(typeName);
  const types = head + [...shapes].map(([t, s]) => `/** ${t} */\nexport interface ${typeName(t)} ${toTs(withLiteral(s, t))}\n`).join('\n')
    + `\nexport type PayPalWebhookEvent = ${names.join(' | ') || 'never'};\n`;
  const zod = head + `import { z } from 'zod';\n\n` + [...shapes].map(([t, s]) => `export const ${typeName(t)}Schema = ${toZod(withLiteral(s, t))};\n`).join('\n')
    + `\nexport const PayPalWebhookEventSchema = z.discriminatedUnion('event_type', [${names.map((n) => `${n}Schema`).join(', ')}]);\n`;
  return { types, zod };
}

// event_type becomes a literal so the union discriminates.
function withLiteral(s: Shape, t: string): Shape {
  if (s.kind !== 'object') return s;
  return { kind: 'object', fields: { ...s.fields, event_type: { shape: { kind: `'${t}'` as any }, optional: false } } };
}

// ---------- drift ----------
export interface Drift { eventType: string; path: string; change: 'removed' | 'added' | 'type-changed' | 'possible-rename'; detail: string }

export function drift(eventType: string, snap: Shape, now: Shape, path = ''): Drift[] {
  const label = (s: Shape) => (s.kind === 'object' ? 'object' : toTs(s));
  if (snap.kind === 'object' && now.kind === 'object') {
    const out: Drift[] = [];
    const removed: string[] = [], added: string[] = [];
    for (const [k, f] of Object.entries(snap.fields)) {
      const n = now.fields[k];
      if (!n) { if (!f.optional) removed.push(k); continue; }
      out.push(...drift(eventType, f.shape, n.shape, `${path}.${k}`));
    }
    for (const k of Object.keys(now.fields)) if (!snap.fields[k]) added.push(k);
    for (const r of removed) {
      const twin = added.find((a) => same(snap.fields[r].shape, now.fields[a].shape));
      if (twin) { added.splice(added.indexOf(twin), 1); out.push({ eventType, path: `${path}.${r}`, change: 'possible-rename', detail: `${path}.${r} is gone and ${path}.${twin} appeared with the same shape` }); }
      else out.push({ eventType, path: `${path}.${r}`, change: 'removed', detail: `field ${path}.${r} is missing` });
    }
    for (const a of added) out.push({ eventType, path: `${path}.${a}`, change: 'added', detail: `new field ${path}.${a}: ${label(now.fields[a].shape)}` });
    return out;
  }
  if (snap.kind === 'array' && now.kind === 'array') return drift(eventType, snap.of, now.of, `${path}[]`);
  if (now.kind === 'unknown' || snap.kind === 'unknown' || same(merge(snap, now), snap)) return [];
  return [{ eventType, path: path || '.', change: 'type-changed', detail: `${path || 'event'} was ${label(snap)}, now ${label(now)}` }];
}

/** Write types and validators, compare each event type with its snapshot, then update snapshots. */
export function run(eventsDir: string, outDir = '.', snapDir = '.paydrill/snapshots') {
  const shapes = shapesByType(loadEvents(eventsDir));
  const { types, zod } = generate(shapes);
  writeFileSync(join(outDir, 'paypal-events.ts'), types);
  writeFileSync(join(outDir, 'paypal-events.zod.ts'), zod);
  mkdirSync(snapDir, { recursive: true });
  const drifts: Drift[] = [];
  for (const [t, s] of shapes) {
    const p = join(snapDir, `${t}.json`);
    if (existsSync(p)) drifts.push(...drift(t, JSON.parse(readFileSync(p, 'utf8')), s));
    else writeFileSync(p, JSON.stringify(s, null, 2) + '\n');
  }
  // ponytail: snapshots are only written the first time; delete a snapshot to accept a drift
  return { types: shapes.size, drifts };
}
